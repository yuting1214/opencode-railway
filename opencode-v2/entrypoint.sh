#!/bin/bash
set -e

# ════════════════════════════════════════════════════════════
# OpenCode 2 devbox — boot script
#
# Goal: the public Railway domain serves OpenCode 2's web UI, and when you
# `railway ssh` into this service and type `opencode`, the TUI attaches to
# that SAME server — one set of sessions, from browser or terminal. Auth,
# sessions and repos live on the /workspace volume and survive redeploys.
# ════════════════════════════════════════════════════════════

# ── Volume layout ───────────────────────────────────────────
mkdir -p /workspace/opencode/data \
         /workspace/opencode/config \
         /workspace/repos \
         /workspace/.ssh \
         /workspace/logs
chmod 700 /workspace/.ssh

# OpenCode keeps its database, auth and logs under ~/.local/share/opencode and
# its config (including the service password, service.json) under
# ~/.config/opencode. Point both at the volume. Unless a path is already our
# symlink, remove whatever is there first — `ln` into a real dir would drop the
# link inside it and leave state on the ephemeral container layer.
mkdir -p /root/.local/share /root/.config
for link in /root/.local/share/opencode /root/.config/opencode; do
    [ -L "$link" ] || rm -rf "$link"
done
ln -sfn /workspace/opencode/data   /root/.local/share/opencode
ln -sfn /workspace/opencode/config /root/.config/opencode
ln -sfn /workspace/.ssh            /root/.ssh

# ── Git / SSH bootstrap ─────────────────────────────────────
# Generate an ed25519 key on first boot (persists via the volume).
if [ ! -f /workspace/.ssh/id_ed25519 ]; then
    echo "[boot] generating ed25519 git key (first boot)..."
    ssh-keygen -t ed25519 -C "opencode-devbox@$(hostname)" \
        -f /workspace/.ssh/id_ed25519 -N "" -q
fi
chmod 600 /workspace/.ssh/id_ed25519 2>/dev/null || true
chmod 644 /workspace/.ssh/id_ed25519.pub 2>/dev/null || true

if ! grep -q "^github.com" /workspace/.ssh/known_hosts 2>/dev/null; then
    echo "[boot] trusting github.com host keys..."
    ssh-keyscan -t rsa,ecdsa,ed25519 github.com 2>/dev/null \
        >> /workspace/.ssh/known_hosts || true
    chmod 644 /workspace/.ssh/known_hosts
fi

git config --global init.defaultBranch main 2>/dev/null || true
[ -n "$GIT_USER_EMAIL" ] && git config --global user.email "$GIT_USER_EMAIL" 2>/dev/null || true
[ -n "$GIT_USER_NAME" ]  && git config --global user.name  "$GIT_USER_NAME"  2>/dev/null || true

# gh auth — re-run each boot if GITHUB_TOKEN is provided.
if [ -n "$GITHUB_TOKEN" ] && command -v gh >/dev/null 2>&1; then
    if ! gh auth status >/dev/null 2>&1; then
        echo "[boot] authenticating gh CLI from GITHUB_TOKEN..."
        echo "$GITHUB_TOKEN" | gh auth login --with-token 2>/dev/null \
            || echo "[boot] gh auth login failed (token may be invalid)"
    fi
fi

# ── Server password ─────────────────────────────────────────
# The server is on a PUBLIC Railway domain, so its API MUST be protected. The
# web UI shell itself loads without a password; every API call needs it, with
# username "opencode". Use OPENCODE_PASSWORD (or the 1.x name,
# OPENCODE_SERVER_PASSWORD), else generate one on first boot and persist it.
#
# `serve --service` reads its password from service.json, NOT the environment
# (it would otherwise invent its own), so write ours there on every boot. The
# TUI over SSH reads the same file, which is why it attaches without a prompt.
OPENCODE_PASSWORD="${OPENCODE_PASSWORD:-$OPENCODE_SERVER_PASSWORD}"
if [ -z "$OPENCODE_PASSWORD" ]; then
    PWFILE=/workspace/.opencode-web-password
    if [ ! -f "$PWFILE" ]; then
        head -c 18 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | cut -c1-24 > "$PWFILE"
        chmod 600 "$PWFILE"
    fi
    OPENCODE_PASSWORD="$(cat "$PWFILE")"
fi
opencode service set password "$OPENCODE_PASSWORD" >/dev/null
unset OPENCODE_PASSWORD OPENCODE_SERVER_PASSWORD
echo "[boot] opencode web auth → user: opencode  password: $(grep -o '"password": *"[^"]*"' /root/.config/opencode/service.json | cut -d'"' -f4)"

# ── Provider keys into SSH login shells ─────────────────────
# `railway ssh` opens a login shell; mirror selected vars into /etc/profile.d so
# the TUI sees your provider keys the moment you connect. (You can also run
# `opencode auth login` instead.) No keys at all is fine: OpenCode's free
# models work without one.
echo "[boot] writing /etc/profile.d/00-opencode-env.sh for SSH shells..."
{
    echo "# Auto-generated by entrypoint.sh on each boot."
    for var in ANTHROPIC_API_KEY OPENAI_API_KEY OPENROUTER_API_KEY GITHUB_TOKEN; do
        val="${!var:-}"
        [ -n "$val" ] && printf 'export %s=%q\n' "$var" "$val"
    done
    # Land in your repos directory on login.
    echo 'cd /workspace/repos 2>/dev/null || true'
} > /etc/profile.d/00-opencode-env.sh
chmod 644 /etc/profile.d/00-opencode-env.sh

echo "[boot] web UI → public Railway domain.  TUI → railway ssh then 'opencode' (same sessions)."
exec "$@"
